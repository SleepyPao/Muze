#!/usr/bin/env python3
"""Pre-record Pip's voice OFFLINE with Piper (neural TTS that runs on this computer; nothing is sent anywhere).

    python3 tools/voice/make_voice.py --model path/to/en_US-kristin-medium.onnx --espeak-data path/to/espeak-ng-data

Needs:  pip install piper-tts lameenc   and the voice model files (.onnx + .onnx.json), see tools/voice/README.md.
Writes: assets/voice/<hash>.mp3 (mono MP3) and js/voice-data.js (text -> [file, seconds]).
Re-run it whenever Pip's lines change (tools/voice/lines.js collects them)."""
import argparse, hashlib, io, json, os, subprocess, sys, wave

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', required=True)
    ap.add_argument('--espeak-data', default=None, help='espeak-ng-data dir (use a SHORT path: espeak-ng fails on paths > 160 chars)')
    ap.add_argument('--length-scale', type=float, default=1.1, help='> 1 = slower, clearer speech for young learners')
    ap.add_argument('--volume', type=float, default=0.85)
    ap.add_argument('--kbps', type=int, default=48)
    a = ap.parse_args()

    from piper import PiperVoice, SynthesisConfig
    import lameenc

    lines = json.loads(subprocess.check_output(['node', os.path.join(ROOT, 'tools', 'voice', 'lines.js')]))
    kw = {'espeak_data_dir': a.espeak_data} if a.espeak_data else {}
    voice = PiperVoice.load(a.model, **kw)
    cfg = SynthesisConfig(length_scale=a.length_scale, noise_scale=0.55, noise_w_scale=0.7, volume=a.volume)
    outdir = os.path.join(ROOT, 'assets', 'voice')
    os.makedirs(outdir, exist_ok=True)
    keep, table = set(), {}
    for text in lines:
        name = hashlib.sha1(text.encode('utf-8')).hexdigest()[:12] + '.mp3'
        buf = io.BytesIO()
        with wave.open(buf, 'wb') as w:
            voice.synthesize_wav(text.replace('…', '...'), w, syn_config=cfg)
        buf.seek(0)
        with wave.open(buf, 'rb') as r:
            rate, ch, frames = r.getframerate(), r.getnchannels(), r.readframes(r.getnframes())
            secs = r.getnframes() / float(rate)
        enc = lameenc.Encoder()
        enc.set_bit_rate(a.kbps); enc.set_in_sample_rate(rate); enc.set_channels(ch); enc.set_quality(2)
        mp3 = enc.encode(frames) + enc.flush()
        with open(os.path.join(outdir, name), 'wb') as f:
            f.write(mp3)
        keep.add(name)
        table[text] = ['assets/voice/' + name, round(secs, 2)]
        print('%5.2fs  %s' % (secs, text))
    for f in os.listdir(outdir):                      # drop clips of lines that no longer exist
        if f.endswith('.mp3') and f not in keep:
            os.remove(os.path.join(outdir, f))
    js = ('/* GENERATED by tools/voice/make_voice.py - do not edit. Pip\'s pre-recorded voice (offline, Piper TTS,\n'
          ' * voice "kristin", public-domain LibriVox data). text -> [file, seconds]. See docs/CREDITS.md. */\n'
          'window.MR_VOICE = ' + json.dumps(table, ensure_ascii=False, indent=1, sort_keys=True) + ';\n')
    with open(os.path.join(ROOT, 'js', 'voice-data.js'), 'w', encoding='utf-8') as f:
        f.write(js)
    print('%d clips, %.1f s total' % (len(table), sum(v[1] for v in table.values())))

if __name__ == '__main__':
    main()
